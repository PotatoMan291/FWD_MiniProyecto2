CREATE DATABASE IF NOT EXISTS portal_rrhh CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE portal_rrhh;
CREATE TABLE IF NOT EXISTS rag_documents (
 drive_id VARCHAR(255) PRIMARY KEY, nombre VARCHAR(255) NOT NULL, version VARCHAR(50) NOT NULL, url TEXT NOT NULL, revision VARCHAR(255) NOT NULL, actualizado TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS rag_chunks (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, drive_id VARCHAR(255) NOT NULL, seccion VARCHAR(255) NOT NULL, contenido MEDIUMTEXT NOT NULL, embedding JSON NOT NULL,
 FOREIGN KEY (drive_id) REFERENCES rag_documents(drive_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS rag_sync_state (id INT PRIMARY KEY, page_token TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS rag_logs (id BIGINT AUTO_INCREMENT PRIMARY KEY, colaborador_id VARCHAR(100), pregunta TEXT NOT NULL, agente VARCHAR(60), fragmentos JSON, latencia_ms INT, escalada BOOLEAN, resuelta BOOLEAN, fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
